"""Binary inventory and reverse-engineering status, so every binary is dissected once and later work only queries.

inventory: walk files or directories and record every executable image (PE, ELF, Mach-O) with path, size, SHA-256,
format, machine and bitness, plus PE file and product versions when pefile is importable. Output is a CSV and a
Markdown table; the inventory names binaries and hashes, it copies nothing.
status: for each [[re.targets]] entry, whether the file still matches its recorded hash and which of the catalog
(exports, strings), the decompiled corpus and the call graph already exist under the data root.
"""
import csv
import hashlib
import json
import os
import struct
from pathlib import Path

PE_MACHINES = {0x014C: ("i386", 32), 0x8664: ("x86-64", 64), 0x01C0: ("arm", 32), 0xAA64: ("arm64", 64), 0x0200: ("ia64", 64)}
ELF_MACHINES = {3: "i386", 62: "x86-64", 40: "arm", 183: "aarch64", 8: "mips", 20: "ppc", 21: "ppc64"}
MACHO_MAGIC = {0xFEEDFACE: 32, 0xFEEDFACF: 64, 0xCEFAEDFE: 32, 0xCFFAEDFE: 64}
COLUMNS = ["path", "size", "sha256", "format", "machine", "bits", "file_version", "product_version"]


def identify(path):
    """(format, machine, bits) for an executable image, or None."""
    try:
        with open(path, "rb") as handle:
            head = handle.read(4096)
    except OSError:
        return None
    if head[:2] == b"MZ" and len(head) >= 0x40:
        offset = struct.unpack_from("<I", head, 0x3C)[0]
        try:
            with open(path, "rb") as handle:
                handle.seek(offset)
                signature = handle.read(6)
        except OSError:
            return None
        if signature[:4] == b"PE\0\0":
            machine, bits = PE_MACHINES.get(struct.unpack_from("<H", signature, 4)[0], ("unknown", 0))
            return "PE", machine, bits
        return None
    if head[:4] == b"\x7fELF" and len(head) >= 20:
        bits = 32 if head[4] == 1 else 64
        endian = "<" if head[5] == 1 else ">"
        return "ELF", ELF_MACHINES.get(struct.unpack_from(endian + "H", head, 18)[0], "unknown"), bits
    if len(head) >= 4:
        magic = struct.unpack_from(">I", head, 0)[0]
        if magic in MACHO_MAGIC:
            return "Mach-O", "", MACHO_MAGIC[magic]
        if magic in (0xCAFEBABE, 0xBEBAFECA) and len(head) >= 8 and struct.unpack_from(">I", head, 4)[0] < 32:
            return "Mach-O universal", "", 0
    return None


def pe_versions(path):
    try:
        import pefile
    except ImportError:
        return "", ""
    try:
        image = pefile.PE(str(path), fast_load=True)
        image.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_RESOURCE"]])
        fixed = image.VS_FIXEDFILEINFO[0] if getattr(image, "VS_FIXEDFILEINFO", None) else None
    except Exception:
        return "", ""
    if not fixed:
        return "", ""
    version = lambda ms, ls: f"{ms >> 16}.{ms & 0xFFFF}.{ls >> 16}.{ls & 0xFFFF}"
    return version(fixed.FileVersionMS, fixed.FileVersionLS), version(fixed.ProductVersionMS, fixed.ProductVersionLS)


def sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def files(inputs):
    for item in inputs:
        item = Path(item)
        if item.is_file():
            yield item
        elif item.is_dir():
            for base, dirs, names in os.walk(item):
                dirs.sort()
                for name in sorted(names):
                    path = Path(base) / name
                    if path.is_file() and not path.is_symlink():
                        yield path


def inventory(inputs, relative_to=None):
    rows = []
    for path in files(inputs):
        kind = identify(path)
        if not kind:
            continue
        file_version, product_version = pe_versions(path) if kind[0] == "PE" else ("", "")
        shown = path.relative_to(relative_to).as_posix() if relative_to and Path(relative_to) in path.parents else str(path)
        rows.append({"path": shown, "size": path.stat().st_size, "sha256": sha256(path), "format": kind[0],
                     "machine": kind[1], "bits": kind[2], "file_version": file_version, "product_version": product_version})
    return rows


def write(rows, csv_path):
    csv_path = Path(csv_path)
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with open(csv_path, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(rows)
    markdown = csv_path.with_suffix(".md")
    lines = [f"# Binary inventory", "", f"Generated by `theseus re inventory`; {len(rows)} executable images.", "",
             "| Path | Format | Machine | Bits | File version | Size | SHA-256 |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for row in rows:
        lines.append(f"| `{row['path']}` | {row['format']} | {row['machine']} | {row['bits']} | {row['file_version']} | "
                     f"{row['size']} | `{row['sha256'][:16]}` |")
    markdown.write_text("\n".join(lines) + "\n")
    return csv_path, markdown


def status(conf):
    """One dict per target: hash state and which analysis artifacts exist."""
    from . import catalog
    rows = []
    for entry in catalog.targets(conf):
        path = entry["path"]
        row = {"target": entry["name"], "file": "missing", "catalog": "-", "corpus": "-", "calls": "-"}
        if path.exists():
            actual = sha256(path)
            row["file"] = "ok" if not entry["sha256"] or actual == entry["sha256"] else "HASH MISMATCH"
        if entry["sha256"]:
            base = catalog.directory(conf, entry)
            if (base / "exports.tsv").exists():
                row["catalog"] = "built"
            index = base / "decompiled" / "decompile-index.json"
            if index.exists():
                try:
                    functions = json.loads(index.read_text()).get("functions", [])
                    row["corpus"] = f"{sum(1 for f in functions if f.get('status') == 'written')} functions"
                except ValueError:
                    row["corpus"] = "unreadable"
            if (base / "decompiled" / "calls.tsv").exists():
                row["calls"] = "built"
        rows.append(row)
    return rows
