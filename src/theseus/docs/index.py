"""Generate docs/investigations/README.md (one row per report with its task ID and section headings) and the listing of
folded reports, so agents scan an index instead of opening reports."""
import json
import re

from .. import config as cfg

SKIP = {"README.md", "TEMPLATE.md"}
TASK_LINE = re.compile(r"^Tasks?:?\s+`([a-z0-9]+(?:-[a-z0-9]+)*)`", re.MULTILINE)
TASK_INLINE = re.compile(r"\bTask\s+`([a-z0-9]+(?:-[a-z0-9]+)*)`")
KEBAB = re.compile(r"`([a-z0-9]+(?:-[a-z0-9]+)+)`")
HEAD = 3000
NO_TOPIC = {"A", "archive-only"}
CLASSES = {"C", "S", "D", "H"} | NO_TOPIC
HEADER = ["| Report | Title | Task | Sections | Size |", "| --- | --- | --- | --- | --- |"]


def known_tasks(root):
    ids = set()
    try:
        ids |= {task["id"] for task in json.loads((root / cfg.TASKS).read_text())["tasks"]}
        archive = root / cfg.ARCHIVE
        if archive.exists():
            ids |= {json.loads(line)["id"] for line in archive.read_text().splitlines() if line.strip()}
    except (OSError, ValueError, KeyError):
        pass
    return ids


def find_task(text, known):
    head = text[:HEAD]
    for pattern in (TASK_LINE, TASK_INLINE):
        match = pattern.search(head)
        if match:
            return match.group(1)
    return next((m.group(1) for m in KEBAB.finditer(head) if m.group(1) in known), None)


def read_fold_map(root):
    """Rows of FOLD-MAP.tsv as dicts (stem, class, topic, successor, line); the header and comments are skipped."""
    path = root / cfg.FOLDED / "FOLD-MAP.tsv"
    rows = []
    if not path.exists():
        return rows
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#") or line.startswith("stem\t"):
            continue
        cells = line.split("\t") + [""] * 4
        rows.append({"stem": cells[0], "class": cells[1], "topic": cells[2], "successor": cells[3], "line": number})
    return rows


def title_of(text, fallback):
    return next((line[2:].strip() for line in text.splitlines() if line.startswith("# ")), fallback)


def row(path, directory, known):
    text = path.read_text(errors="replace")
    task = find_task(text, known)
    sections = [line[3:].strip() for line in text.splitlines() if line.startswith("## ")]
    covered = "; ".join(sections[:5]) + ("; ..." if len(sections) > 5 else "")
    return (f"| [{path.stem}]({path.relative_to(directory).as_posix()}) | {title_of(text, path.stem).replace('|', '/')} | "
            f"{f'`{task}`' if task else ''} | {covered.replace('|', '/')} | {len(text) // 1024} KB |")


def render(root):
    directory = root / cfg.REPORTS
    paths = sorted(p for p in directory.glob("*.md") if p.name not in SKIP)
    archived = sorted(p for p in (directory / "archive").glob("*.md") if p.name not in SKIP)
    known = known_tasks(root)
    lines = [
        "# Investigations",
        "",
        f"Generated by `theseus docs index`; do not edit by hand. {len(paths)} active reports and {len(archived)} archived in `archive/`. "
        f"Search the active reports with `rg -n PATTERN {cfg.REPORTS} --glob '!archive'`; look up cited addresses and captures in "
        f"the citation index (`theseus docs index` writes it). New reports follow `TEMPLATE.md`; living subsystem documents are in `{cfg.TOPICS}/`.",
        "",
        *HEADER,
        *(row(path, directory, known) for path in paths),
    ]
    if archived:
        lines += ["", "## Archived", "", *HEADER, *(row(path, directory, known) for path in archived)]
    lines += ["", f"Folded reports are listed in `{cfg.FOLDED}/INDEX.md`."]
    return "\n".join(lines) + "\n"


def render_folded(root):
    directory = root / cfg.FOLDED
    entries = {e["stem"]: e for e in read_fold_map(root)}
    paths = sorted(p for p in directory.glob("*.md") if p.name not in SKIP | {"INDEX.md"})
    known = known_tasks(root)
    lines = [
        "# Folded investigations",
        "",
        f"Generated by `theseus docs index`; do not edit by hand. {len(paths)} reports moved here unchanged after their content was "
        f"folded into a topic document in `{cfg.TOPICS}/`. Cite the topic document in new work, not these files.",
        "",
        "| Report | Title | Class | Topic | Successor | Task | Size |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for path in sorted(paths, key=lambda p: (entries.get(p.stem, {}).get("topic", ""), p.stem)):
        text = path.read_text(errors="replace")
        entry = entries.get(path.stem, {})
        task = find_task(text, known)
        lines.append(f"| [{path.stem}]({path.name}) | {title_of(text, path.stem).replace('|', '/')} | {entry.get('class', '')} | "
                     f"{entry.get('topic', '')} | {entry.get('successor', '')} | {f'`{task}`' if task else ''} | {len(text) // 1024} KB |")
    return "\n".join(lines) + "\n"


def folded_problems(root):
    directory = root / cfg.FOLDED
    problems, seen = [], {}
    for entry in read_fold_map(root):
        if entry["stem"] in seen:
            problems.append(f"FOLD-MAP.tsv:{entry['line']}: duplicate stem {entry['stem']}")
        seen[entry["stem"]] = entry
        if entry["class"] not in CLASSES:
            problems.append(f"FOLD-MAP.tsv:{entry['line']}: unknown class {entry['class']!r} for {entry['stem']}")
    for path in sorted(directory.glob("*.md")):
        if path.name in SKIP | {"INDEX.md"}:
            continue
        entry = seen.get(path.stem)
        if entry is None:
            problems.append(f"{path.name} has no FOLD-MAP.tsv row")
        elif entry["class"] not in NO_TOPIC and not (root / cfg.TOPICS / f"{entry['topic']}.md").exists():
            problems.append(f"{path.name}: FOLD-MAP.tsv names missing topic {entry['topic']!r}")
    return problems


def outputs(root):
    return {root / cfg.REPORTS / "README.md": render(root), root / cfg.FOLDED / "INDEX.md": render_folded(root)}


def write(root):
    written = []
    for path, text in outputs(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
        written.append(path.relative_to(root).as_posix())
    return written


def check(root):
    problems = [f"{p.relative_to(root)} is stale; run `theseus docs index`"
                for p, text in outputs(root).items() if not p.exists() or p.read_text() != text]
    return problems + folded_problems(root)
