"""Generate docs/re/citation-index.md: every cited native address, capture reference or other configured citation in
the docs, with where it is cited and which evidence IDs share that line.

The index is mechanical. It adds no names or interpretations; the cited line is the authority. Citation kinds come from
[re] citations in theseus.toml, so a device-protocol port can index capture references (file hash plus frame) the same
way a binary port indexes addresses.
"""
import re

from .. import config as cfg

SNIPPET = 240
ARCHIVED_SNIPPET = 80
ARCHIVED_MARKER = " (archived)"


class Citations:
    def __init__(self, re_section):
        self.kinds = []
        low = int(re_section.get("address_low") or 0)
        high = int(re_section.get("address_high") or 0)
        for entry in re_section.get("citations") or []:
            self.kinds.append({"name": entry["name"], "regex": re.compile(entry["pattern"]),
                               "format": entry.get("format", "text"), "low": int(entry.get("low", low) or 0),
                               "high": int(entry.get("high", high) or 0)})
        self.evidence = re.compile(re_section.get("evidence") or r"(?!x)x")

    def find(self, text):
        """Normalized citations in text, as (kind, value) pairs."""
        found = set()
        for kind in self.kinds:
            for match in kind["regex"].finditer(text):
                token = match.group(1) if match.groups() else match.group(0)
                if kind["format"] == "hex":
                    value = int(token, 16)
                    if value < kind["low"] or (kind["high"] and value >= kind["high"]):
                        continue
                    token = f"0x{value:08x}"
                found.add((kind["name"], token))
        return found

    def evidence_ids(self, text):
        return set(self.evidence.findall(text))


def of(conf):
    return Citations(conf.section("re"))


def archived(parts):
    return parts[:3] == ("project", "archive", "investigations")


def snippet(line, evidence, limit):
    text = re.sub(r"\s*\|\s*", " / ", line.strip().strip("|")).replace("`", "")
    text = evidence.sub(lambda m: m.group(0)[:15] + "...", text)
    return text if len(text) <= limit else text[: limit - 3] + "..."


def collect(root, citations, index_path=cfg.CITATION_INDEX):
    rows = []
    docs = root / "docs"
    if not docs.is_dir():
        return rows
    for path in sorted(docs.rglob("*.md")):
        parts = path.relative_to(docs).parts
        if path == root / index_path or (parts[:2] == ("project", "archive") and not archived(parts)):
            continue
        old = archived(parts)
        relative = path.relative_to(root).as_posix() + (ARCHIVED_MARKER if old else "")
        for number, line in enumerate(path.read_text(errors="replace").splitlines(), 1):
            found = citations.find(line)
            if not found:
                continue
            ids = sorted(citations.evidence_ids(line))
            for kind, value in found:
                rows.append((kind, value, relative, number, ids,
                             snippet(line, citations.evidence, ARCHIVED_SNIPPET if old else SNIPPET)))
    rows.sort(key=lambda r: (r[0], r[1], r[2], r[3]))
    return rows


def render(rows):
    values = len({(r[0], r[1]) for r in rows})
    documents = len({r[2].removesuffix(ARCHIVED_MARKER) for r in rows})
    out = [
        "# Citation index",
        "",
        f"Generated by `theseus docs index`; do not edit by hand. {values} distinct citations, cited {len(rows)} times across {documents} documents.",
        "",
        "Every row is a citation, not a name assignment: read the cited line and its evidence before relying on it. "
        "Look up a native address with `theseus re find ADDRESS` (local catalog, never committed).",
        "",
        "| Kind | Value | Cited at | Evidence on that line | Cited text |",
        "| --- | --- | --- | --- | --- |",
    ]
    for kind, value, relative, number, ids, text in rows:
        place = relative.removesuffix(ARCHIVED_MARKER) + f":{number}" + (ARCHIVED_MARKER if relative.endswith(ARCHIVED_MARKER) else "")
        shown = ", ".join(e[:15] + "..." for e in ids)
        out.append(f"| {kind} | {value} | {place} | {shown} | {text.replace('|', '/')} |")
    return "\n".join(out) + "\n"


def write(conf):
    path = conf.root / cfg.citation_index(conf)
    text = render(collect(conf.root, of(conf), cfg.citation_index(conf)))
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    return [cfg.citation_index(conf)]


def check(conf):
    path = conf.root / cfg.citation_index(conf)
    if not path.exists() or path.read_text() != render(collect(conf.root, of(conf), cfg.citation_index(conf))):
        return [f"{cfg.citation_index(conf)} is stale; run `theseus docs index`"]
    return []
